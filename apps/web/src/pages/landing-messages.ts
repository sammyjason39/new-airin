type LandingMessageTree = (typeof landingMessages)["id"];

/** String fields stay string across locales; list fields keep their shape. */
export type LandingMessages = {
  [K in keyof LandingMessageTree]: LandingMessageTree[K] extends string
    ? string
    : LandingMessageTree[K];
};

export function getLandingMessages(locale: AppLocale): LandingMessages {
  return (landingMessages[locale] ?? landingMessages.id) as LandingMessages;
}
